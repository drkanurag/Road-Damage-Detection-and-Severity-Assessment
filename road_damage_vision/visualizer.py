"""
Visualization engine for rendering annotated bounding boxes, severity badges,
and an executive Pavement Condition HUD onto road inspection images.
"""

from typing import List, Optional, Tuple, Union
import cv2
import numpy as np
from PIL import Image

from road_damage_vision.config import (
    ROAD_STATUS_CRITICAL,
    ROAD_STATUS_FAIR,
    ROAD_STATUS_GOOD,
    ROAD_STATUS_POOR,
    SEVERITY_COLORS_BGR,
    SEVERITY_HIGH,
    SEVERITY_LOW,
    SEVERITY_MEDIUM,
)
from road_damage_vision.detector import Detection, RoadDamageReport


class RoadDamageVisualizer:
    """
    Renders professional, publication-quality annotations onto road images.
    """

    def __init__(
        self,
        show_hud: bool = True,
        show_severity_badge: bool = True,
        show_confidence: bool = True,
        line_thickness: Optional[int] = None,
        font_scale: Optional[float] = None,
    ):
        self.show_hud = show_hud
        self.show_severity_badge = show_severity_badge
        self.show_confidence = show_confidence
        self.line_thickness = line_thickness
        self.font_scale = font_scale

    def draw(
        self,
        image_input: Union[str, np.ndarray, Image.Image],
        report: RoadDamageReport,
        highlight_id: Optional[int] = None,
    ) -> np.ndarray:
        """
        Draws defect bounding boxes, severity pills, and HUD summary on image.

        Args:
            image_input: Image path, numpy BGR array, or PIL Image.
            report: RoadDamageReport generated by detector.
            highlight_id: Optional detection ID to highlight prominently.

        Returns:
            Annotated BGR image as numpy array.
        """
        if isinstance(image_input, str):
            canvas = cv2.imread(image_input)
            if canvas is None:
                raise ValueError(f"Could not load image: {image_input}")
        elif isinstance(image_input, Image.Image):
            canvas = cv2.cvtColor(np.array(image_input), cv2.COLOR_RGB2BGR)
        elif isinstance(image_input, np.ndarray):
            canvas = image_input.copy()
        else:
            raise TypeError(f"Unsupported image type: {type(image_input)}")

        h_img, w_img = canvas.shape[:2]

        # Dynamic thickness and font scaling relative to image resolution
        base_dim = max(h_img, w_img)
        thickness = self.line_thickness or max(2, int(base_dim / 350))
        font_scale = self.font_scale or max(0.48, base_dim / 1300.0)

        # 1. Draw each detected bounding box
        for det in report.detections:
            color = SEVERITY_COLORS_BGR.get(det.severity.level, (0, 255, 0))
            x1, y1, x2, y2 = [int(v) for v in det.bbox]

            is_highlighted = highlight_id is not None and det.id == highlight_id
            curr_thick = thickness + 2 if is_highlighted else thickness

            # Draw outer bounding box
            cv2.rectangle(canvas, (x1, y1), (x2, y2), color, curr_thick, cv2.LINE_AA)

            # Draw corner accents for high aesthetic clarity
            corner_len = min(20, int((x2 - x1) * 0.25), int((y2 - y1) * 0.25))
            if corner_len > 4:
                accent_color = (255, 255, 255)
                accent_thick = max(1, curr_thick - 1)
                # Top-left
                cv2.line(canvas, (x1, y1), (x1 + corner_len, y1), accent_color, accent_thick)
                cv2.line(canvas, (x1, y1), (x1, y1 + corner_len), accent_color, accent_thick)
                # Top-right
                cv2.line(canvas, (x2, y1), (x2 - corner_len, y1), accent_color, accent_thick)
                cv2.line(canvas, (x2, y1), (x2, y1 + corner_len), accent_color, accent_thick)
                # Bottom-left
                cv2.line(canvas, (x1, y2), (x1 + corner_len, y2), accent_color, accent_thick)
                cv2.line(canvas, (x1, y2), (x1, y2 - corner_len), accent_color, accent_thick)
                # Bottom-right
                cv2.line(canvas, (x2, y2), (x2 - corner_len, y2), accent_color, accent_thick)
                cv2.line(canvas, (x2, y2), (x2, y2 - corner_len), accent_color, accent_thick)

            # Label text formatting
            label_parts = [f"#{det.id} {det.class_name}"]
            if self.show_confidence:
                label_parts.append(f"{int(det.confidence * 100)}%")
            if self.show_severity_badge:
                label_parts.append(f"[{det.severity.level.upper()}]")

            label_str = " | ".join(label_parts)

            # Compute text dimensions
            (text_w, text_h), baseline = cv2.getTextSize(
                label_str, cv2.FONT_HERSHEY_SIMPLEX, font_scale, thickness=1
            )
            pad_x, pad_y = 6, 4

            # Place label above box, or inside if too close to top
            lbl_y1 = max(0, y1 - text_h - 2 * pad_y)
            lbl_y2 = lbl_y1 + text_h + 2 * pad_y
            lbl_x1 = max(0, x1)
            lbl_x2 = min(w_img, lbl_x1 + text_w + 2 * pad_x)

            # Filled pill background
            cv2.rectangle(canvas, (lbl_x1, lbl_y1), (lbl_x2, lbl_y2), color, -1)
            # Subtle dark inner border for contrast
            cv2.rectangle(canvas, (lbl_x1, lbl_y1), (lbl_x2, lbl_y2), (20, 20, 20), 1)

            # Text label
            text_x = lbl_x1 + pad_x
            text_y = lbl_y2 - pad_y - 2
            # Use white or dark text based on background color luminance
            cv2.putText(
                canvas,
                label_str,
                (text_x, text_y),
                cv2.FONT_HERSHEY_SIMPLEX,
                font_scale,
                (255, 255, 255),
                1,
                cv2.LINE_AA,
            )

        # 2. Draw Executive HUD Header
        if self.show_hud:
            canvas = self._render_executive_hud(canvas, report)

        return canvas

    def _render_executive_hud(self, img: np.ndarray, report: RoadDamageReport) -> np.ndarray:
        """Draws top HUD banner with Road Health Score, Condition Status, and Breakdown."""
        h_img, w_img = img.shape[:2]
        hud_h = max(56, int(h_img * 0.085))

        overlay = img.copy()
        cv2.rectangle(overlay, (0, 0), (w_img, hud_h), (18, 22, 28), -1)
        # Semi-transparent blending for sleek modern HUD
        alpha = 0.88
        img = cv2.addWeighted(overlay, alpha, img, 1 - alpha, 0)

        # Status badge color
        status = report.summary.status
        if status == ROAD_STATUS_GOOD:
            status_bgr = (94, 197, 34)
        elif status == ROAD_STATUS_FAIR:
            status_bgr = (11, 158, 245)
        elif status == ROAD_STATUS_POOR:
            status_bgr = (45, 110, 245)
        else:
            status_bgr = (68, 68, 239)

        font_hud = cv2.FONT_HERSHEY_SIMPLEX
        font_sz = max(0.44, hud_h / 125.0)

        # Left Section: Health Score & Condition
        score_text = f"PCI HEALTH: {report.summary.health_score:.0f}/100 [{status.upper()}]"
        cv2.putText(
            img,
            score_text,
            (16, int(hud_h * 0.45)),
            font_hud,
            font_sz * 1.15,
            status_bgr,
            2,
            cv2.LINE_AA,
        )

        sub_text = f"Urgency: {report.summary.estimated_maintenance_urgency.split(':')[0]}"
        cv2.putText(
            img,
            sub_text,
            (16, int(hud_h * 0.82)),
            font_hud,
            font_sz * 0.85,
            (210, 215, 220),
            1,
            cv2.LINE_AA,
        )

        # Right Section: Defect Counts and Severity Breakdown
        counts = report.summary.severity_counts
        counts_text = (
            f"Defects: {report.summary.total_defects} | "
            f"High: {counts.get(SEVERITY_HIGH, 0)} | "
            f"Med: {counts.get(SEVERITY_MEDIUM, 0)} | "
            f"Low: {counts.get(SEVERITY_LOW, 0)}"
        )
        (tw, _), _ = cv2.getTextSize(counts_text, font_hud, font_sz, 1)
        right_x = max(int(w_img * 0.5), w_img - tw - 24)

        cv2.putText(
            img,
            counts_text,
            (right_x, int(hud_h * 0.45)),
            font_hud,
            font_sz,
            (255, 255, 255),
            1,
            cv2.LINE_AA,
        )

        perf_text = f"Latency: {report.inference_time_ms:.1f}ms | {report.backend_used}"
        cv2.putText(
            img,
            perf_text,
            (right_x, int(hud_h * 0.82)),
            font_hud,
            font_sz * 0.80,
            (160, 170, 180),
            1,
            cv2.LINE_AA,
        )

        return img

    def create_thumbnail_grid(
        self,
        image_input: Union[str, np.ndarray, Image.Image],
        report: RoadDamageReport,
        thumb_size: int = 180,
    ) -> List[Tuple[Detection, np.ndarray]]:
        """
        Extracts cropped and labeled thumbnail crops for each detected defect.

        Returns:
            List of (Detection, thumbnail_bgr_image) tuples.
        """
        if isinstance(image_input, str):
            orig_img = cv2.imread(image_input)
        elif isinstance(image_input, Image.Image):
            orig_img = cv2.cvtColor(np.array(image_input), cv2.COLOR_RGB2BGR)
        else:
            orig_img = image_input

        h_img, w_img = orig_img.shape[:2]
        thumbnails = []

        for det in report.detections:
            x1, y1, x2, y2 = [int(v) for v in det.bbox]
            # Add 10% context padding around the defect
            bw = x2 - x1
            bh = y2 - y1
            pad_x = int(bw * 0.12)
            pad_y = int(bh * 0.12)

            cx1 = max(0, x1 - pad_x)
            cy1 = max(0, y1 - pad_y)
            cx2 = min(w_img, x2 + pad_x)
            cy2 = min(h_img, y2 + pad_y)

            crop = orig_img[cy1:cy2, cx1:cx2]
            if crop.size > 0:
                thumb = cv2.resize(crop, (thumb_size, thumb_size), interpolation=cv2.INTER_AREA)
                # Border in severity color
                color = SEVERITY_COLORS_BGR.get(det.severity.level, (0, 255, 0))
                cv2.rectangle(thumb, (0, 0), (thumb_size - 1, thumb_size - 1), color, 3)
                thumbnails.append((det, thumb))

        return thumbnails
